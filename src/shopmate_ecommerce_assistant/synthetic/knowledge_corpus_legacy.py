"""Stage-17 corpus expansion — superseded (legacy) versions of the original policies.

Every original policy that previously had a single ``2026.10.1`` version now
also carries the version it replaced, so "the same question, a different
answer" becomes a first-class retrieval test: a query dated inside the legacy
window (2026-07-01 → 2026-10-01) must cite the legacy version, and a query
dated after 2026-10-01 must cite the current one.

The legacy numbers are deliberately different from the current ones (warranty
months, price-protection days, free-shipping threshold, dispatch hours …).
That is what stops retrieval from being a pure semantic-similarity exercise:
the lexical signal (the number itself) has to agree with the version filter.

All content is written for this project; no real merchant, brand or regulation
is described.
"""

