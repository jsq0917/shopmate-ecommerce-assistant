def _with_annexes(doc: PolicyDoc) -> PolicyDoc:
    extra = _EXTRA_SECTIONS.get(f"{doc.key}@{doc.version}", ())
    annex = _ANNEX_SECTIONS.get(f"{doc.key}@{doc.version}", ())
    current = _CURRENT_ANNEX.get(doc.key, ()) if doc.version == "2026.10.1" else ()
    boundary = _CURRENT_BOUNDARY.get(doc.key, ()) if doc.version == "2026.10.1" else ()
    return _normalise_effective_from(
        replace(doc, sections=doc.sections + extra + annex + current + boundary)
    )


