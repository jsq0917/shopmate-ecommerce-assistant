def faq_records() -> list[dict[str, Any]]:
    """Return the 50 FAQ rows with stable ids."""
    records: list[dict[str, Any]] = []
    for index, (question, answer, category, doc_key) in enumerate(FAQ_ENTRIES, start=1):
        records.append(
            {
                "id": f"faq-{index:03d}",
                "question": question,
                "answer": answer,
                "category": category,
                "locale": "zh-CN",
                "region": "SG" if doc_key.endswith("-sg") else "CN",
                "policy_document_key": doc_key,
                "is_synthetic": True,
                "tags": ["synthetic", "faq", category],
            }
        )
    return records


def manifest_payload() -> dict[str, Any]:
    """Return the ingest manifest for every policy version."""
    documents = []
    for doc in POLICY_DOCS:
        documents.append(
            {
                "document_key": doc.key,
                "title": doc.title,
                "doc_type": doc.doc_type,
                "version": doc.version,
                "effective_from": doc.effective_from,
                "effective_to": doc.effective_to,
                "locale": "zh-CN",
                "region": doc.region,
                "knowledge_base": doc.knowledge_base,
                "file": f"policy/{doc.filename}",
                "is_synthetic": True,
            }
        )
    return {
        "manifest_version": 1,
        "generated_by": "scripts/seed.py",
        "shop_key": "demo",
        "documents": documents,
    }


def dumps_rows(rows: list[dict[str, Any]]) -> str:
    """Serialize rows as JSON Lines with stable key order."""
    return "\n".join(json.dumps(row, ensure_ascii=False, sort_keys=True) for row in rows) + "\n"
