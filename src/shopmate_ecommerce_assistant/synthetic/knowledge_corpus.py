"""Synthetic policy corpus, FAQ entries and evaluation questions.

The content is written for this project. It is coherent enough to support retrieval,
citation and refusal tests, and it is explicitly fictional: no real merchant, regulation or
customer is described.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, replace
from typing import Any

KB_CN = "policy-cn"
KB_SG = "policy-sg"


@dataclass(frozen=True, slots=True)
class Section:
    """A heading with its paragraphs."""

    heading: str
    paragraphs: tuple[str, ...]


@dataclass(frozen=True, slots=True)
class PolicyDoc:
    """One synthetic policy document version."""

    key: str
    title: str
    doc_type: str
    region: str
    knowledge_base: str
    version: str
    effective_from: str
    effective_to: str | None
    file_format: str
    sections: tuple[Section, ...]

    @property
    def filename(self) -> str:
        return f"{self.key}-{self.version}.{self.file_format}"


def _doc(
    key: str,
    title: str,
    *,
    doc_type: str,
    version: str,
    effective_from: str,
    sections: tuple[Section, ...],
    region: str = "CN",
    knowledge_base: str = KB_CN,
    effective_to: str | None = None,
    file_format: str = "md",
) -> PolicyDoc:
    return PolicyDoc(
        key=key,
        title=title,
        doc_type=doc_type,
        region=region,
        knowledge_base=knowledge_base,
        version=version,
        effective_from=effective_from,
        effective_to=effective_to,
        file_format=file_format,
        sections=sections,
    )


